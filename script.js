document.addEventListener('DOMContentLoaded', () => {
  // Determine current language, default to 'en'
  let currentLang = localStorage.getItem('site_lang') || 'en';
  
  const updateLanguage = (lang) => {
    // Select all elements with data-i18n attribute
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      if (langData[lang][key]) {
        // Handle input placeholders vs regular text content
        if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
            el.placeholder = langData[lang][key];
        } else {
            el.textContent = langData[lang][key];
        }
      }
    });
    
    // Set active link color based on current URL path
    const path = window.location.pathname;
    const page = path.split("/").pop();
    document.querySelectorAll('.nav-links a').forEach(link => {
      const href = link.getAttribute('href');
      if (href === page || (page === '' && href === 'index.html')) {
        link.classList.add('active');
      } else {
        link.classList.remove('active');
      }
    });
  };

  // Initial load
  updateLanguage(currentLang);

  // Toggle button event
  const langToggleBtn = document.getElementById('langToggle');
  if (langToggleBtn) {
    langToggleBtn.addEventListener('click', () => {
      currentLang = currentLang === 'en' ? 'vi' : 'en';
      localStorage.setItem('site_lang', currentLang);
      updateLanguage(currentLang);
    });
  }
  // Mobile Menu Toggle
  const mobileMenu = document.getElementById('mobile-menu');
  const navLinks = document.querySelector('.nav-links');
  
  if (mobileMenu) {
    mobileMenu.addEventListener('click', () => {
      navLinks.classList.toggle('active');
    });
  }
});
